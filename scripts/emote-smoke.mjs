// 手机触控模拟：打开表情面板 → 发动画表情 → 发快捷语；检查气泡和用时显示。用法：node scripts/emote-smoke.mjs [站点] [截图目录]
import { chromium, devices } from 'playwright';
const root = process.argv[2] ?? 'http://localhost:5188/';
const dir = process.argv[3] ?? '.';
const b = await chromium.launch(process.env.QI_RESOLVE ? { args: [`--host-resolver-rules=${process.env.QI_RESOLVE}`] } : {});
const p = await (await b.newContext({ ...devices['Pixel 7'] })).newPage();
p.on('pageerror', (e) => console.log('pageerror:', e.message));
p.on('console', (m) => m.type() === 'error' && console.log('console error:', m.text()));
await p.goto(root + '#/play?game=xiangqi&mode=ai&side=white&level=1&t=' + Date.now());
await p.waitForSelector('cg-board piece');
await p.waitForTimeout(2200);
console.log('用时：', (await p.locator('.player-time').allTextContents()).join(' / '));
await p.locator('.emote-btn').tap();
await p.waitForSelector('.emote-grid svg', { timeout: 10000 });
await p.waitForTimeout(500);
console.log('面板：表情', await p.locator('.emote-cell').count(), '个，快捷语', await p.locator('.phrase-chip').count(), '条，已渲染动画', await p.locator('.emote-cell svg').count());
await p.screenshot({ path: dir + '/emote-picker.png' });
await p.locator('.emote-cell').first().tap();
await p.waitForSelector('.emote-bubble svg', { timeout: 10000 });
await p.waitForTimeout(400);
await p.screenshot({ path: dir + '/emote-bubble.png' });
console.log('动画表情气泡出现');
await p.waitForTimeout(1400);
await p.locator('.emote-btn').tap();
await p.locator('.phrase-chip').first().tap();
await p.waitForSelector('.emote-bubble.phrase', { timeout: 5000 });
await p.waitForTimeout(350);
console.log('快捷语气泡：', await p.locator('.emote-bubble.phrase').textContent());
await p.screenshot({ path: dir + '/emote-phrase.png' });
await p.waitForTimeout(3000);
console.log('气泡 2.6 秒后消失：', (await p.locator('.emote-bubble').count()) === 0);
await b.close();
